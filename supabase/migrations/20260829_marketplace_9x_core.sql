create table if not exists public.book_reviews (
  id uuid primary key default gen_random_uuid(),
  book_id uuid not null references public.books(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  purchase_id uuid references public.book_purchases(id) on delete set null,
  rating smallint not null check (rating between 1 and 5),
  title text,
  review text,
  verified_purchase boolean not null default false,
  helpful_count integer not null default 0 check (helpful_count >= 0),
  status text not null default 'published' check (status in ('pending','published','hidden','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (book_id, user_id)
);

create index if not exists book_reviews_book_status_idx
  on public.book_reviews(book_id, status, created_at desc);
create index if not exists book_reviews_user_idx
  on public.book_reviews(user_id, created_at desc);

create or replace function public.set_book_review_verified_purchase()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  matched_purchase uuid;
begin
  select bp.id
    into matched_purchase
  from public.book_purchases bp
  where bp.book_id = new.book_id
    and bp.user_id = new.user_id
    and lower(coalesce(bp.status, '')) in ('paid','completed','approved','succeeded')
  order by coalesce(bp.paid_at, bp.created_at) desc
  limit 1;

  new.purchase_id := matched_purchase;
  new.verified_purchase := matched_purchase is not null;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists book_reviews_verify_purchase on public.book_reviews;
create trigger book_reviews_verify_purchase
before insert or update of book_id, user_id, rating, title, review
on public.book_reviews
for each row execute function public.set_book_review_verified_purchase();

