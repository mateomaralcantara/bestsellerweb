  on public.book_editorial_versions(book_id)
  where is_current;

create or replace function public.set_book_editorial_version_current()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.is_current then
    update public.book_editorial_versions
       set is_current = false
     where book_id = new.book_id
       and id <> new.id
       and is_current = true;
  end if;
  return new;
end;
$$;

drop trigger if exists book_editorial_versions_current on public.book_editorial_versions;
create trigger book_editorial_versions_current
after insert or update of is_current
on public.book_editorial_versions
for each row execute function public.set_book_editorial_version_current();

