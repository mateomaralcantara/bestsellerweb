join public.book_bestseller_scores bs on bs.book_id = b.id;

-- ============================================================
-- 8. SEARCH 2.0: FTS + TRIGRAM + RANKING
-- ============================================================
create or replace function public.search_marketplace_books(
  p_query text,
  p_category text default null,
  p_limit integer default 24,
  p_offset integer default 0
)
returns table (
  book_id uuid,
  slug text,
  title text,
  subtitle text,
  cover_url text,
  primary_category text,
  primary_niche text,
  verified_rating numeric,
  verified_sales_count bigint,
  bestseller_score numeric,
  relevance numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  with query_parts as (
    select
      nullif(trim(coalesce(p_query,'')), '') as raw_q,
      websearch_to_tsquery('simple', coalesce(nullif(trim(p_query),''), '')) as tsq
  ), candidates as (
    select
      b.*,
      vm.verified_rating,
      vm.verified_sales_count,
      bs.bestseller_score,
      setweight(to_tsvector('simple', coalesce(b.title,'')), 'A') ||
      setweight(to_tsvector('simple', coalesce(b.subtitle,'')), 'A') ||
      setweight(to_tsvector('simple', coalesce(array_to_string(b.keywords,' '),'')), 'B') ||
      setweight(to_tsvector('simple', coalesce(b.primary_category,'')), 'B') ||
      setweight(to_tsvector('simple', coalesce(b.primary_niche,'')), 'B') ||
      setweight(to_tsvector('simple', coalesce(b.description_short,'')), 'C') ||
      setweight(to_tsvector('simple', coalesce(b.description_long,'')), 'D') as document,
      qp.raw_q,
      qp.tsq
    from public.books b
    cross join query_parts qp
    left join public.book_verified_metrics vm on vm.book_id = b.id
    left join public.book_bestseller_scores bs on bs.book_id = b.id
    where lower(coalesce(b.status::text,'')) = 'published'
      and (
        p_category is null or trim(p_category) = '' or
        lower(coalesce(b.primary_category,'')) = lower(trim(p_category)) or
        lower(coalesce(b.primary_niche,'')) = lower(trim(p_category)) or
        lower(coalesce(b.secondary_category,'')) = lower(trim(p_category))
      )
  )
  select
    c.id,
    c.slug,
    c.title,
    c.subtitle,
    c.cover_url,
    c.primary_category,
    c.primary_niche,
    coalesce(c.verified_rating,0),
    coalesce(c.verified_sales_count,0),
    coalesce(c.bestseller_score,0),
    case
      when c.raw_q is null then coalesce(c.bestseller_score,0)
      else round((
          ts_rank_cd(c.document, c.tsq, 32) * 100
        + similarity(lower(coalesce(c.title,'')), lower(c.raw_q)) * 40
        + similarity(lower(coalesce(c.subtitle,'')), lower(c.raw_q)) * 15
        + least(coalesce(c.bestseller_score,0),100) * 0.05
      )::numeric, 4)
    end as relevance
  from candidates c
  where c.raw_q is null
     or c.document @@ c.tsq
     or similarity(lower(coalesce(c.title,'')), lower(c.raw_q)) > 0.15
     or similarity(lower(coalesce(c.subtitle,'')), lower(c.raw_q)) > 0.15
  order by relevance desc, c.title asc
  limit greatest(1, least(coalesce(p_limit,24),100))
  offset greatest(coalesce(p_offset,0),0);
$$;

-- ============================================================
-- 9. RECOMENDACIONES V1 EXPLICABLES
-- ============================================================
create or replace function public.recommend_marketplace_books(
  p_user_id uuid,
  p_limit integer default 12
)
returns table (
  book_id uuid,
  slug text,
  title text,
  cover_url text,
  reason text,
  score numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  with purchased as (
    select distinct b.primary_category, b.primary_niche
    from public.book_purchases bp
    join public.books b on b.id = bp.book_id
    where bp.user_id = p_user_id
      and lower(coalesce(bp.status,'')) in ('paid','completed','approved','succeeded')
  ), already_owned as (
    select distinct bp.book_id
    from public.book_purchases bp
    where bp.user_id = p_user_id
      and lower(coalesce(bp.status,'')) in ('paid','completed','approved','succeeded')
  )
  select
    b.id,
    b.slug,
    b.title,
    b.cover_url,
    case
      when exists (
        select 1 from purchased p
        where p.primary_category is not null
          and lower(p.primary_category) = lower(b.primary_category)
      ) then 'Porque lees esta categoría'
      when exists (
        select 1 from purchased p
        where p.primary_niche is not null
          and lower(p.primary_niche) = lower(b.primary_niche)
      ) then 'Relacionado con tus lecturas'
      else 'Tendencia en LibroSeller'
    end as reason,
    round((
      coalesce(bs.bestseller_score,0) * 0.55
      + coalesce(vm.verified_rating,0) * 5 * 0.15
      + case when exists (
          select 1 from purchased p
          where lower(coalesce(p.primary_category,'')) = lower(coalesce(b.primary_category,''))
        ) then 20 else 0 end
      + case when exists (
          select 1 from purchased p
          where lower(coalesce(p.primary_niche,'')) = lower(coalesce(b.primary_niche,''))
        ) then 10 else 0 end
    )::numeric,4) as score
  from public.books b
  left join public.book_bestseller_scores bs on bs.book_id = b.id
  left join public.book_verified_metrics vm on vm.book_id = b.id
  where lower(coalesce(b.status::text,'')) = 'published'
    and not exists (select 1 from already_owned ao where ao.book_id = b.id)
  order by score desc, b.created_at desc nulls last
  limit greatest(1, least(coalesce(p_limit,12),50));
$$;

