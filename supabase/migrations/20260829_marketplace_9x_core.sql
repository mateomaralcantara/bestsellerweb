alter table public.epub_preflight_reports enable row level security;
alter table public.book_editorial_versions enable row level security;

drop policy if exists "Public can read published book reviews" on public.book_reviews;
create policy "Public can read published book reviews"
on public.book_reviews for select
to anon, authenticated
using (status = 'published');

drop policy if exists "Users can manage own reviews" on public.book_reviews;
create policy "Users can manage own reviews"
on public.book_reviews for all
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- Eventos se insertan únicamente desde el servidor con service role.
revoke all on table public.marketplace_events from anon, authenticated;
revoke all on table public.epub_preflight_reports from anon, authenticated;
revoke all on table public.book_editorial_versions from anon, authenticated;
grant all on table public.marketplace_events to service_role;
grant all on table public.epub_preflight_reports to service_role;
grant all on table public.book_editorial_versions to service_role;
grant all on table public.book_reviews to service_role;

grant select on public.book_verified_metrics to anon, authenticated, service_role;
grant select on public.book_bestseller_scores to anon, authenticated, service_role;
grant select on public.author_book_analytics to service_role;
grant execute on function public.search_marketplace_books(text,text,integer,integer) to anon, authenticated, service_role;
grant execute on function public.recommend_marketplace_books(uuid,integer) to authenticated, service_role;

