-- ============================================================
-- 7. SEARCH 2.0 - compatible con columnas/keywords históricos
-- ============================================================
drop function if exists public.search_marketplace_books(text,text,integer,integer);

create function public.search_marketplace_books(
  p_query text,
  p_category text default null,
  p_limit integer default 24,
  p_offset integer default 0
)
returns table (
  book_id uuid,
  slug text,
  title text,
  subtitle text,
  cover_url text,
  primary_category text,
  primary_niche text,
  verified_rating numeric,
  verified_sales_count bigint,
  bestseller_score numeric,
  relevance numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  with query_parts as (
    select
      nullif(trim(coalesce(p_query,'')), '') as raw_q,
      case
        when nullif(trim(coalesce(p_query,'')), '') is null then null::tsquery
        else websearch_to_tsquery('simple', trim(p_query))
      end as tsq
  ), candidates as (
    select
      b.id,
      (to_jsonb(b)->>'slug')::text as slug,
      (to_jsonb(b)->>'title')::text as title,
      (to_jsonb(b)->>'subtitle')::text as subtitle,
      (to_jsonb(b)->>'cover_url')::text as cover_url,
      (to_jsonb(b)->>'primary_category')::text as primary_category,
      (to_jsonb(b)->>'primary_niche')::text as primary_niche,
      coalesce(vm.verified_rating,0)::numeric as verified_rating,
      coalesce(vm.verified_sales_count,0)::bigint as verified_sales_count,
      coalesce(bs.bestseller_score,0)::numeric as bestseller_score,
      (
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'title','')), 'A') ||
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'subtitle','')), 'A') ||
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'keywords','')), 'B') ||
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'primary_category','')), 'B') ||
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'primary_niche','')), 'B') ||
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'description_short','')), 'C') ||
        setweight(to_tsvector('simple', coalesce(to_jsonb(b)->>'description_long','')), 'D')
      ) as document,
      qp.raw_q,
      qp.tsq
    from public.books b
    cross join query_parts qp
    left join public.book_verified_metrics vm on vm.book_id = b.id
    left join public.book_bestseller_scores bs on bs.book_id = b.id
    where lower(coalesce(to_jsonb(b)->>'status','')) = 'published'
      and (
        p_category is null or trim(p_category) = ''
        or lower(coalesce(to_jsonb(b)->>'primary_category','')) = lower(trim(p_category))
        or lower(coalesce(to_jsonb(b)->>'primary_niche','')) = lower(trim(p_category))
        or lower(coalesce(to_jsonb(b)->>'secondary_category','')) = lower(trim(p_category))
      )
  ), scored as (
    select
      c.*,
      case when c.raw_q is null then c.bestseller_score
      else round((
          coalesce(ts_rank_cd(c.document,c.tsq,32),0) * 100
        + similarity(lower(coalesce(c.title,'')), lower(c.raw_q)) * 40
        + similarity(lower(coalesce(c.subtitle,'')), lower(c.raw_q)) * 15
        + least(c.bestseller_score,100) * 0.05
      )::numeric,4) end as computed_relevance
    from candidates c
  )
  select
    s.id::uuid,
    s.slug,
    s.title,
    s.subtitle,
    s.cover_url,
    s.primary_category,
    s.primary_niche,
    s.verified_rating,
    s.verified_sales_count,
    s.bestseller_score,
    s.computed_relevance
  from scored s
  where s.raw_q is null
     or s.document @@ s.tsq
     or similarity(lower(coalesce(s.title,'')), lower(s.raw_q)) > 0.15
     or similarity(lower(coalesce(s.subtitle,'')), lower(s.raw_q)) > 0.15
  order by s.computed_relevance desc, s.title asc
  limit greatest(1, least(coalesce(p_limit,24),100))
  offset greatest(coalesce(p_offset,0),0);
$$;

