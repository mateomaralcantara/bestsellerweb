-- 4. MÉTRICAS VERIFICADAS
-- ============================================================
create or replace view public.book_verified_metrics as
with purchases as (
  select
    bp.book_id,
    count(*) filter (
      where lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
    )::bigint as verified_sales_count,
    count(*) filter (
      where lower(coalesce(bp.status::text,'')) in ('refunded','revoked')
    )::bigint as refund_count,
    coalesce(sum(bp.amount_paid) filter (
      where lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
    ),0)::numeric as gross_revenue
  from public.book_purchases bp
  group by bp.book_id
), reviews as (
  select
    br.book_id,
    count(*) filter (where lower(coalesce(br.status::text,'')) = 'published')::bigint as review_count,
    coalesce(avg(br.rating) filter (where lower(coalesce(br.status::text,'')) = 'published'),0)::numeric(4,2) as verified_rating
  from public.book_reviews br
  group by br.book_id
), events as (
  select
    me.book_id,
    count(*) filter (where me.event_type = 'book_impression')::bigint as impressions,
    count(*) filter (where me.event_type = 'book_click')::bigint as clicks,
    count(*) filter (where me.event_type = 'preview_started')::bigint as preview_starts,
    count(*) filter (where me.event_type = 'preview_completed')::bigint as preview_completions,
    count(*) filter (where me.event_type = 'checkout_started')::bigint as checkout_starts,
    count(*) filter (where me.event_type = 'reader_completed')::bigint as reader_completions
  from public.marketplace_events me
  group by me.book_id
)
select
  b.id as book_id,
  coalesce(p.verified_sales_count,0)::bigint as verified_sales_count,
  coalesce(p.refund_count,0)::bigint as refund_count,
  coalesce(p.gross_revenue,0)::numeric as gross_revenue,
  coalesce(r.review_count,0)::bigint as review_count,
  coalesce(r.verified_rating,0)::numeric(4,2) as verified_rating,
  coalesce(e.impressions,0)::bigint as impressions,
  coalesce(e.clicks,0)::bigint as clicks,
  coalesce(e.preview_starts,0)::bigint as preview_starts,
  coalesce(e.preview_completions,0)::bigint as preview_completions,
  coalesce(e.checkout_starts,0)::bigint as checkout_starts,
  coalesce(e.reader_completions,0)::bigint as reader_completions,
  case when coalesce(e.impressions,0) > 0
    then round((coalesce(e.clicks,0)::numeric / e.impressions) * 100, 2)
    else 0::numeric end as click_through_rate,
  case when coalesce(e.preview_starts,0) > 0
    then round((coalesce(p.verified_sales_count,0)::numeric / e.preview_starts) * 100, 2)
    else 0::numeric end as preview_to_purchase_rate
from public.books b
left join purchases p on p.book_id = b.id
left join reviews r on r.book_id = b.id
left join events e on e.book_id = b.id;

-- ============================================================
-- 5. BESTSELLER SCORE
-- ============================================================
create or replace view public.book_bestseller_scores as
with recent_sales as (
  select
    bp.book_id,
    count(*) filter (
      where lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
        and coalesce(bp.paid_at,bp.created_at) >= now() - interval '24 hours'
    )::numeric as sales_24h,
    count(*) filter (
      where lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
        and coalesce(bp.paid_at,bp.created_at) >= now() - interval '7 days'
    )::numeric as sales_7d,
    count(*) filter (
      where lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
        and coalesce(bp.paid_at,bp.created_at) >= now() - interval '30 days'
    )::numeric as sales_30d
  from public.book_purchases bp
  group by bp.book_id
), recent_events as (
  select
    me.book_id,
    count(*) filter (
      where me.event_type = 'book_click'
        and me.occurred_at >= now() - interval '7 days'
    )::numeric as clicks_7d,
    count(*) filter (
      where me.event_type = 'reader_completed'
        and me.occurred_at >= now() - interval '30 days'
    )::numeric as completions_30d
  from public.marketplace_events me
  group by me.book_id
)
select
  b.id as book_id,
  coalesce(s.sales_24h,0)::numeric as sales_24h,
  coalesce(s.sales_7d,0)::numeric as sales_7d,
  coalesce(s.sales_30d,0)::numeric as sales_30d,
  coalesce(vm.verified_rating,0)::numeric as rating,
  coalesce(e.clicks_7d,0)::numeric as clicks_7d,
  coalesce(e.completions_30d,0)::numeric as completions_30d,
  round((
      coalesce(s.sales_24h,0) * 0.30
    + coalesce(s.sales_7d,0) * 0.25
    + coalesce(s.sales_30d,0) * 0.10
    + least(coalesce(vm.preview_to_purchase_rate,0),100) * 0.15
    + coalesce(vm.verified_rating,0) * 2 * 0.10
    + least(coalesce(e.completions_30d,0),100) * 0.10
  )::numeric,4) as bestseller_score
from public.books b
left join recent_sales s on s.book_id = b.id
left join recent_events e on e.book_id = b.id
left join public.book_verified_metrics vm on vm.book_id = b.id;

