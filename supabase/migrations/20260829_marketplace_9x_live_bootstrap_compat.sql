-- 8. RECOMENDACIONES V1
-- ============================================================
drop function if exists public.recommend_marketplace_books(uuid,integer);

create function public.recommend_marketplace_books(
  p_user_id uuid,
  p_limit integer default 12
)
returns table (
  book_id uuid,
  slug text,
  title text,
  cover_url text,
  reason text,
  score numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  with purchased as (
    select distinct
      (to_jsonb(b)->>'primary_category')::text as primary_category,
      (to_jsonb(b)->>'primary_niche')::text as primary_niche
    from public.book_purchases bp
    join public.books b on b.id = bp.book_id
    where bp.user_id = p_user_id
      and lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
  ), already_owned as (
    select distinct bp.book_id
    from public.book_purchases bp
    where bp.user_id = p_user_id
      and lower(coalesce(bp.status::text,'')) in ('paid','completed','approved','succeeded')
  )
  select
    b.id::uuid,
    (to_jsonb(b)->>'slug')::text,
    (to_jsonb(b)->>'title')::text,
    (to_jsonb(b)->>'cover_url')::text,
    case
      when exists (
        select 1 from purchased p
        where nullif(p.primary_category,'') is not null
          and lower(p.primary_category) = lower(coalesce(to_jsonb(b)->>'primary_category',''))
      ) then 'Porque lees esta categoría'
      when exists (
        select 1 from purchased p
        where nullif(p.primary_niche,'') is not null
          and lower(p.primary_niche) = lower(coalesce(to_jsonb(b)->>'primary_niche',''))
      ) then 'Relacionado con tus lecturas'
      else 'Tendencia en LibroSeller'
    end::text,
    round((
        coalesce(bs.bestseller_score,0)::numeric * 0.55
      + coalesce(vm.verified_rating,0)::numeric * 5 * 0.15
      + case when exists (
          select 1 from purchased p
          where lower(coalesce(p.primary_category,'')) = lower(coalesce(to_jsonb(b)->>'primary_category',''))
        ) then 20 else 0 end
      + case when exists (
          select 1 from purchased p
          where lower(coalesce(p.primary_niche,'')) = lower(coalesce(to_jsonb(b)->>'primary_niche',''))
        ) then 10 else 0 end
    )::numeric,4)
  from public.books b
  left join public.book_bestseller_scores bs on bs.book_id = b.id
  left join public.book_verified_metrics vm on vm.book_id = b.id
  where lower(coalesce(to_jsonb(b)->>'status','')) = 'published'
    and not exists (select 1 from already_owned ao where ao.book_id = b.id)
  order by 6 desc, 3 asc
  limit greatest(1, least(coalesce(p_limit,12),50));
$$;

